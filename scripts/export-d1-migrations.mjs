/**
 * Writes the D1 migrations from the schema the Node server actually creates,
 * and the catalogue it actually seeds, rather than from a hand-copy of either.
 *
 * Two files come out: 0001 is the seven tables and three indexes, read back out
 * of sqlite_master so the D1 schema cannot drift from the one the integration
 * tests run against; 0002 is the 111 seeded dishes with the ids the app already
 * ships in its bundled catalogue, so a tablet's offline order still matches a
 * product after the backend moves.
 */
import { mkdtempSync, readdirSync, rmSync, unlinkSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { createDatabase } from "../server/database.mjs";
import { dishPhotos } from "../server/dish-photos.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const files = {
  schema: path.join(root, "migrations", "0001_init.sql"),
  catalog: path.join(root, "migrations", "0002_seed_catalog.sql")
};

const SEEDED_AT = "2026-01-01T00:00:00.000Z";

function quote(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

function withSeededDatabase(run) {
  const directory = mkdtempSync(path.join(tmpdir(), "zy-d1-"));
  try {
    const file = path.join(directory, "seed.sqlite");
    createDatabase(file).close();
    const db = new DatabaseSync(file);
    try {
      return run(db);
    } finally {
      db.close();
    }
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

export function generate() {
  return withSeededDatabase((db) => {
    // rootpage order follows creation order, which is the order the tables are
    // declared in server/database.mjs — so a table is created after the one it
    // references, and the file reads the way the schema was written.
    const objects = db.prepare(
      "SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, rootpage"
    ).all();

    const schema = [
      "-- Generated by scripts/export-d1-migrations.mjs. Do not edit by hand.",
      "-- Source of truth: the CREATE statements in server/database.mjs.",
      "",
      ...objects.map((object) => `${object.sql.trim()};`),
      ""
    ].join("\n");

    const products = db.prepare("SELECT * FROM products ORDER BY sort_order, id").all();
    const columns = Object.keys(products[0]);
    // The Node server stamps these with the moment it seeded. A migration has to
    // produce the same file every time it is generated, so the shipped catalogue
    // carries one fixed timestamp; the restaurant's own edits overwrite it.
    const seededAt = { created_at: SEEDED_AT, updated_at: SEEDED_AT };
    const rows = products.map((product) => `  (${columns.map((column) => quote({ ...product, ...seededAt }[column])).join(", ")})`);
    const catalog = [
      "-- Generated by scripts/export-d1-migrations.mjs. Do not edit by hand.",
      `-- The ${products.length} dishes server/photo-menu.mjs seeds, with the ids the`,
      "-- customer app already ships in bundled-catalog.json.",
      "",
      `INSERT INTO products (${columns.join(", ")}) VALUES`,
      `${rows.join(",\n")};`,
      ""
    ].join("\n");

    return { schema, catalog };
  });
}

/**
 * The dish photos, as bytes, for D1 — which a Worker can read and a deploy
 * cannot otherwise write to. Split so no file is much over ~1.5 MB: D1 takes a
 * migration as one request, and a single statement (one photo, hex-encoded)
 * must stay under its 100 KB limit, which the fetcher's 45 KB cap guarantees.
 *
 * Each photo is attached only to a dish that exists and has no picture yet,
 * so a restaurant that already uploaded its own keeps it.
 */
const PHOTO_FILE_BUDGET = 1_500_000;
const PHOTO_MIGRATION_FIRST = 5;

export function generatePhotos() {
  const schema = withSeededDatabase((db) => db.prepare("SELECT sql FROM sqlite_master WHERE name = 'media_files'").get().sql);
  const photos = dishPhotos();
  const chunks = [];
  let current = [];
  let size = 0;
  for (const photo of photos) {
    const statement = [
      `INSERT OR IGNORE INTO media_files (id, content_type, bytes, credit, source_url, created_at) VALUES (${quote(photo.fileId)}, ${quote(photo.contentType)}, X'${photo.bytes.toString("hex")}', ${quote(photo.credit)}, ${quote(photo.sourceUrl)}, ${quote(SEEDED_AT)});`,
      `INSERT INTO product_media (id, product_id, type, url, poster_url, sort_order, created_at) SELECT ${quote(`seed-${photo.fileId}`)}, ${quote(photo.productId)}, 'image', ${quote(`/media/${photo.fileId}`)}, NULL, 0, ${quote(SEEDED_AT)} WHERE EXISTS (SELECT 1 FROM products WHERE id = ${quote(photo.productId)}) AND NOT EXISTS (SELECT 1 FROM product_media WHERE product_id = ${quote(photo.productId)});`
    ].join("\n");
    if (current.length && size + statement.length > PHOTO_FILE_BUDGET) {
      chunks.push(current);
      current = [];
      size = 0;
    }
    current.push(statement);
    size += statement.length;
  }
  if (current.length) chunks.push(current);

  return chunks.map((statements, index) => ({
    name: `${String(PHOTO_MIGRATION_FIRST + index).padStart(4, "0")}_dish_photos${index ? `_${index + 1}` : ""}.sql`,
    sql: [
      "-- Generated by scripts/export-d1-migrations.mjs from server/dish-photos/. Do not edit by hand.",
      `-- Dish photos from Wikimedia Commons, part ${index + 1} of ${chunks.length}; credits in server/dish-photos/credits.json.`,
      "",
      // Every part creates the table, so each one stands on its own.
      `${schema.replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS").replace("IF NOT EXISTS IF NOT EXISTS", "IF NOT EXISTS")};`,
      "",
      ...statements,
      ""
    ].join("\n")
  }));
}

const PHOTO_MIGRATION = /^\d{4}_dish_photos(_\d+)?\.sql$/;

function committedPhotos() {
  const directory = path.join(root, "migrations");
  return readdirSync(directory).filter((name) => PHOTO_MIGRATION.test(name)).sort()
    .map((name) => ({ name, sql: readFileSync(path.join(directory, name), "utf8") }));
}

export function committed() {
  return { schema: readFileSync(files.schema, "utf8"), catalog: readFileSync(files.catalog, "utf8"), photos: committedPhotos() };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const generated = generate();
  writeFileSync(files.schema, generated.schema);
  writeFileSync(files.catalog, generated.catalog);
  for (const [name, file] of Object.entries(files)) console.log(`wrote ${name} -> ${path.relative(process.cwd(), file)}`);
  for (const old of committedPhotos()) unlinkSync(path.join(root, "migrations", old.name));
  for (const part of generatePhotos()) {
    writeFileSync(path.join(root, "migrations", part.name), part.sql);
    console.log(`wrote photos -> migrations/${part.name} (${part.sql.length} bytes)`);
  }
}
