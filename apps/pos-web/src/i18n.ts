const copies: Record<PosLanguage, Copy> = { zh, de, en };
export type PosKey = keyof Copy;
export type PosTranslate = (key: PosKey, values?: Record<string, string | number>) => string;

export function translator(language: PosLanguage): PosTranslate {
  return (key, values = {}) => copies[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export function initialLanguage(): PosLanguage {
  try {
    const stored = localStorage.getItem("zy_pos_language");
    if (stored === "zh" || stored === "de" || stored === "en") return stored;
  } catch { /* private mode: the default */ }
  return "zh";
}

export function formatEuro(cents: number, language: PosLanguage): string {
  return new Intl.NumberFormat({ zh: "zh-CN", de: "de-AT", en: "en-GB" }[language], { style: "currency", currency: "EUR" }).format(cents / 100);
}
