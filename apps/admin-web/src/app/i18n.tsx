const copies: Record<AdminLanguage, Copy> = { zh, en, de };

export type CopyKey = keyof Copy;
export type Translate = (key: CopyKey, values?: Record<string, string | number>) => string;

const storageKey = "zy_admin_language";

/** This device's pick, else the browser's language, else Chinese — the
 *  owner's. */
export function initialAdminLanguage(): AdminLanguage {
  try {
    const stored = localStorage.getItem(storageKey);
    if (stored && ADMIN_LANGUAGES.includes(stored as AdminLanguage)) return stored as AdminLanguage;
  } catch { /* Private tab: fall through to the browser's language. */ }
  for (const tag of navigator.languages ?? []) {
    const primary = tag.toLowerCase().split("-")[0] as AdminLanguage;
    if (ADMIN_LANGUAGES.includes(primary)) return primary;
  }
  return "zh";
}

const moneyLocale: Record<AdminLanguage, string> = { zh: "zh-CN", en: "en-GB", de: "de-AT" };

/** Money the way the console's language writes it: "€ 12,50", "€12.50". */
export function formatMoney(cents: number, language: AdminLanguage): string {
  return new Intl.NumberFormat(moneyLocale[language], { style: "currency", currency: "EUR" }).format(cents / 100);
}

/** A clock time in the console's language, for order and table timestamps. */
export function formatTime(value: string, language: AdminLanguage): string {
  return new Date(value).toLocaleTimeString(moneyLocale[language], { hour: "2-digit", minute: "2-digit" });
}

export function translate(language: AdminLanguage, key: CopyKey, values: Record<string, string | number> = {}): string {
  return copies[language][key].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

interface I18n {
  language: AdminLanguage;
  setLanguage: (language: AdminLanguage) => void;
  t: Translate;
}

const I18nContext = createContext<I18n>({
  language: "zh",
  setLanguage: () => undefined,
  t: (key, values) => translate("zh", key, values)
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AdminLanguage>(initialAdminLanguage);
  const setLanguage = useCallback((next: AdminLanguage) => {
    setLanguageState(next);
    document.documentElement.lang = next;
    try { localStorage.setItem(storageKey, next); } catch { /* Kept for this visit only. */ }
  }, []);
  const value = useMemo<I18n>(() => ({
    language,
    setLanguage,
    t: (key, values) => translate(language, key, values)
  }), [language, setLanguage]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  return useContext(I18nContext);
}
